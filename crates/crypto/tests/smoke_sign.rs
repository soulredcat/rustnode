use alephium_crypto::{PrivateKey, PublicKey, sign, verify};

#[test]
fn rust_sign_matches_vector() {
    let message: [u8; 32] = [
        0xd6, 0x65, 0x6c, 0xaf, 0x57, 0xec, 0x78, 0x8f, 0xe5, 0x2b, 0xa9, 0x4d, 0xad, 0xdb, 0x3f,
        0x8f, 0xfc, 0x2f, 0xfa, 0xe3, 0x11, 0xed, 0xe1, 0xe5, 0xc7, 0x6b, 0x85, 0x03, 0xc9, 0x3a,
        0x9c, 0x9b,
    ];

    let mut private_key_bytes = [0u8; 32];
    private_key_bytes[31] = 1;
    let private_key = PrivateKey::try_from(private_key_bytes.as_slice()).unwrap();

    let expected_signature: [u8; 64] = [
        0xa3, 0x25, 0xde, 0xe4, 0x3d, 0x6a, 0x1d, 0x7b, 0x83, 0xbd, 0x2f, 0xac, 0xf7, 0x4a, 0xdb,
        0x75, 0x70, 0x2f, 0xfa, 0xf6, 0x86, 0x9a, 0xf9, 0x5a, 0xdb, 0x38, 0xda, 0xcf, 0x67, 0xdf,
        0xf5, 0x88, 0x68, 0xfd, 0xbf, 0x6c, 0xa6, 0x3f, 0x1c, 0x92, 0xf3, 0x2e, 0x33, 0xf0, 0xd8,
        0x58, 0x99, 0x83, 0xc0, 0x6c, 0x1c, 0xfc, 0x1a, 0x0c, 0x3e, 0x66, 0xea, 0xc3, 0xf4, 0xaa,
        0x4c, 0x08, 0xb7, 0x78,
    ];

    let clique = [
        0x02u8, 0x79, 0xbe, 0x66, 0x7e, 0xf9, 0xdc, 0xbb, 0xac, 0x55, 0xa0, 0x62, 0x95, 0xce, 0x87,
        0x0b, 0x07, 0x02, 0x9b, 0xfc, 0xdb, 0x2d, 0xce, 0x28, 0xd9, 0x59, 0xf2, 0x81, 0x5b, 0x16,
        0xf8, 0x17, 0x98,
    ];

    let signature = sign(&message, &private_key).unwrap();
    assert_eq!(&signature.bytes()[..], &expected_signature);

    let public_key = PublicKey::try_from(clique.as_slice()).unwrap();
    assert!(verify(&message, &signature, &public_key));
}
